class TestGuardianSchemaAndBackwardCompat:
    """Tests 24-27: Pydantic schema validation, defaults, and coordinator output projection."""

    def test_minimal_valid_guardian_result(self):
        """TEST 24: Minimal instantiation requires safety_assessment."""
        result = GuardianResult(safety_assessment="All safe")
        assert result.agent == "guardian"
        assert result.status == AgentStatus.COMPLETED
        assert result.risk_level == RiskLevel.LOW
        assert result.safety_risks == []

    def test_full_round_trip(self):
        """TEST 25: Model dump and re-instantiation preserves all attributes."""
        data = json.loads(_make_healthcare_response())
        result = GuardianResult(**data)
        dumped = result.model_dump()
        rehydrated = GuardianResult(**dumped)
        assert rehydrated.safety_assessment == result.safety_assessment
        assert len(rehydrated.safety_risks) == len(result.safety_risks)

    def test_required_fields(self):
        """TEST 26: Omitting required safety_assessment raises error."""
        with pytest.raises(Exception):
            GuardianResult()  # type: ignore[call-arg]

    def test_sensible_defaults(self):
        """TEST 27: Unspecified optional fields default to empty lists or None."""
        r = GuardianResult(safety_assessment="Assessment test")
        assert r.human_oversight is None
        assert r.user_vulnerability is None
        assert r.privacy_considerations == []
        assert r.safeguards == []

    def test_guardian_output_projection_for_coordinator(self):
        """Verify GuardianOutput produces fields required by coordinator.py."""
        data = json.loads(_make_healthcare_response())
        res = GuardianResult(**data)
        out = GuardianOutput.from_guardian_result(res)

        # Check fields accessed by coordinator (e.g. limitations, mitigations)
        dump = out.model_dump()
        assert "safety_and_privacy_risks" in dump
        assert "reliability_and_ethical_risks" in dump
        assert "unsafe_assumptions" in dump
        assert "limitations" in dump
        assert "recommended_mitigations" in dump

        assert len(out.safety_and_privacy_risks) > 0
        assert len(out.recommended_mitigations) > 0
        assert len(out.limitations) > 0
        assert out.guardian_result is res
